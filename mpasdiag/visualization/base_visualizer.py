    def _ensure_boundary_data(
        self: "MPASVisualizer", dataset: Optional[xr.Dataset]
    ) -> Optional[xr.Dataset]:
        """
        This method checks if the provided xarray Dataset contains the necessary cell-boundary coordinate variables ('lon_b' and 'lat_b'). If they are already present, it returns the dataset unchanged. If they are missing but the dataset contains the required mesh topology variables ('verticesOnCell', 'lonVertex', 'latVertex', 'nEdgesOnCell'), it computes the boundary coordinates based on the vertex information and adds 'lon_b' and 'lat_b' to the dataset. The boundaries are built with vectorised indexing and cached at module level, keyed by the mesh topology and vertex coordinates, so every plotter in a process (including the fresh plotter that each parallel task creates) reuses them instead of rebuilding them for each time step. If the dataset does not contain enough information to compute boundaries, it returns the original dataset without modification.

        Parameters:
            dataset (Optional[xr.Dataset]): An xarray Dataset that may or may not contain the 'lon_b' and 'lat_b' variables, and may contain the necessary mesh topology variables to compute them if they are missing.

        Returns:
            Optional[xr.Dataset]: The original dataset if 'lon_b' and 'lat_b' are already present or cannot be computed; otherwise, a new dataset with 'lon_b' and 'lat_b' added based on the mesh topology.
        """
        if dataset is None:
            return None

        if "lon_b" in dataset and "lat_b" in dataset:
            return dataset

        required_mesh_vars = {
            "verticesOnCell",
            "lonVertex",
            "latVertex",
            "nEdgesOnCell",
        }

        if not required_mesh_vars.issubset(dataset.variables.keys()):
            return dataset

        vertices_on_cell = np.asarray(dataset["verticesOnCell"].values)
        vertex_lon = np.asarray(dataset["lonVertex"].values).ravel()
        vertex_lat = np.asarray(dataset["latVertex"].values).ravel()
        cache_key = (
            vertices_on_cell.shape,
            _array_fingerprint(vertices_on_cell),
            _array_fingerprint(np.asarray(dataset["nEdgesOnCell"].values)),
            _array_fingerprint(vertex_lon),
            _array_fingerprint(vertex_lat),
        )

        cached = _SHARED_BOUNDARIES.get(cache_key)
        if cached is None:
            edges_per_cell = np.asarray(dataset["nEdgesOnCell"].values).ravel()
            edges_per_cell = edges_per_cell.astype(np.intp)
            n_vertices = int(np.bincount(edges_per_cell).argmax())
            # Pad short cells by repeating their last vertex; verticesOnCell is 1-indexed
            columns = np.minimum(
                np.arange(n_vertices)[np.newaxis, :], edges_per_cell[:, np.newaxis] - 1
            )
            vertex_index = np.take_along_axis(vertices_on_cell, columns, axis=1) - 1
            cached = (
                vertex_lon[vertex_index].astype(np.float64),
                vertex_lat[vertex_index].astype(np.float64),
            )
            _SHARED_BOUNDARIES.clear()
            _SHARED_BOUNDARIES[cache_key] = cached
        lon_b, lat_b = cached
        return dataset.assign(
            {
                "lon_b": xr.DataArray(lon_b, dims=["nCells", "nv"]),
                "lat_b": xr.DataArray(lat_b, dims=["nCells", "nv"]),
            }
        )

    @staticmethod
    def _extract_full_grid(dataset: xr.Dataset) -> Tuple[np.ndarray, np.ndarray]:
        """
        This static method extracts the full longitude and latitude coordinates for the MPAS cell centers from the provided xarray Dataset. It looks for common variable names that represent longitude and latitude (e.g., 'lonCell', 'latCell', 'lon', 'lat', 'longitude', 'latitude') and retrieves their values, flattening them into 1D arrays. The method then converts the coordinates to degrees if they are in radians, and normalizes longitude values to the range [-180, 180] degrees for consistency in plotting. If the required longitude or latitude variables cannot be found in the dataset, it raises a KeyError with an informative message. This method is essential for obtaining the spatial coordinates needed for mapping MPAS data onto geographic projections.

        Parameters:
            dataset (xr.Dataset): An xarray Dataset containing the longitude and latitude variables for the MPAS cell centers, which may be named in various ways.

        Returns:
            Tuple[np.ndarray, np.ndarray]: A tuple containing two 1D NumPy arrays: the first is the longitude coordinates in degrees (normalized to [-180, 180]), and the second is the latitude coordinates in degrees.
        """
        for lon_key in ("lonCell", "lon", "longitude"):
            if lon_key in dataset:
                lon_raw = dataset[lon_key].values.flatten().astype(float)
                break
        else:
            raise KeyError(
                "Cannot find longitude coordinate (lonCell/lon/longitude) in dataset"
            )
        for lat_key in ("latCell", "lat", "latitude"):
            if lat_key in dataset:
                lat_raw = dataset[lat_key].values.flatten().astype(float)
                break
        else:
            raise KeyError(
                "Cannot find latitude coordinate (latCell/lat/latitude) in dataset"
            )
        lon_deg, lat_deg = _convert_coordinates_to_degrees(lon_raw, lat_raw)
        lon_deg = ((lon_deg + 180) % 360) - 180
        return lon_deg, lat_deg

    @staticmethod
    def _backmap_to_full_grid(
        lon_valid: np.ndarray,
        lat_valid: np.ndarray,
        data_valid: np.ndarray,
        lon_full: np.ndarray,
        lat_full: np.ndarray,
    ) -> np.ndarray:
        """
        This static method performs a back-mapping of data values from a subset of valid longitude and latitude coordinates to the full grid of longitude and latitude coordinates. It uses a KDTree from scipy.spatial to efficiently find the nearest valid point for each full grid point, and assigns the corresponding data value to the full grid. If the distance between a full grid point and its nearest valid point exceeds a small threshold (e.g., 1e-4 degrees), it assigns NaN to that full grid point to indicate that it is not close enough to any valid data point. This method is useful for reconstructing a complete data array on the original MPAS grid after processing or interpolation has been performed on a subset of points.

        Parameters:
            lon_valid (np.ndarray): 1D array of longitude coordinates for the valid data points in degrees.
            lat_valid (np.ndarray): 1D array of latitude coordinates for the valid data points in degrees.
            data_valid (np.ndarray): 1D array of data values corresponding to the valid (lon, lat) points.
            lon_full (np.ndarray): 1D array of longitude coordinates for the full grid in degrees.
            lat_full (np.ndarray): 1D array of latitude coordinates for the full grid in degrees.

        Returns:
            np.ndarray: A 1D array of data values corresponding to the full grid, where values are assigned from data_valid based on the nearest valid point, and NaN is assigned to points that are not close enough to any valid point.
        """
        from scipy.spatial import KDTree

        # compare in one longitude frame: callers may pass 0..360 data against a [-180, 180] grid
        def _wrap(lon: np.ndarray) -> np.ndarray:
            return ((np.asarray(lon, dtype=float) + 180.0) % 360.0) - 180.0

        tree = KDTree(np.column_stack([_wrap(lon_valid), lat_valid]))
        nearest_distances, nearest_indices = tree.query(
            np.column_stack([_wrap(lon_full), lat_full])
        )
        full_data = np.full(len(lon_full), np.nan)
        within_threshold = nearest_distances < 1e-4
        full_data[within_threshold] = data_valid[nearest_indices[within_threshold]]
        return cast(np.ndarray, full_data)

    @staticmethod
    def _align_to_dataset(
        dataset: xr.Dataset,
        lon_valid: Union[np.ndarray, xr.DataArray],
        lat_valid: Union[np.ndarray, xr.DataArray],
        data_valid: Union[np.ndarray, xr.DataArray],
    ) -> np.ndarray:
        """
        This helper returns data values that line up one-to-one with the cells of the dataset handed to the remapper. Plotters drop invalid points (NaN, negative accumulations) before contouring, but the remapper takes its source coordinates from the dataset, so a filtered array no longer matches the dataset's cells and indexing fails or, worse, values land on the wrong cells. When the sizes already agree the data is returned unchanged; otherwise the valid values are placed back on the dataset's full cell list and cells without a valid value become NaN, so missing data stays missing on the remapped grid instead of being filled from a neighbour. A dataset without recognisable cell coordinates is left to the remapper.

        Parameters:
            dataset (xr.Dataset): Dataset whose cell coordinates the remapper will use.
            lon_valid (Union[np.ndarray, xr.DataArray]): Longitudes in degrees of the points in data_valid.
            lat_valid (Union[np.ndarray, xr.DataArray]): Latitudes in degrees of the points in data_valid.
            data_valid (Union[np.ndarray, xr.DataArray]): Data values, possibly a filtered subset of the dataset's cells.

        Returns:
            np.ndarray: Data values with one entry per dataset cell (or the input unchanged when it already matches).
        """
        data_arr = np.asarray(data_valid)
        try:
            lon_full, lat_full = MPASVisualizer._extract_full_grid(dataset)
        except KeyError:
            return data_arr
        if len(lon_full) == len(data_arr):
            return data_arr
        logger.debug(
            "Mapping %d valid points back onto %d dataset cells (missing cells -> NaN)",
            len(data_arr),
            len(lon_full),
        )
        lon_deg = ((np.asarray(lon_valid, dtype=float) + 180) % 360) - 180
        return MPASVisualizer._backmap_to_full_grid(
            lon_deg,
            np.asarray(lat_valid, dtype=float),
            data_arr.astype(float),
            lon_full,
            lat_full,
        )

    def _get_or_build_remapper(
        self: "MPASVisualizer",
        lon_full: np.ndarray,
        lat_full: np.ndarray,
        lon_b: np.ndarray,
        lat_b: np.ndarray,
        lon_min: float,
        lon_max: float,
        lat_min: float,
        lat_max: float,
        resolution: float,
        comm: Optional[Any] = None,
        method: str = "conservative",
    ) -> MPASRemapper:
        """
        This method retrieves a cached MPASRemapper instance if it matches the specified grid configuration and remapping parameters, or builds a new MPASRemapper if the configuration has changed. It constructs a unique key based on the dimensions of the full grid, the geographic bounds, and the resolution to determine if an existing remapper can be reused. If a new remapper is needed, it prepares the source grid using the full longitude and latitude coordinates along with their boundaries, creates a target grid based on the specified geographic extent and resolution, and builds the regridder for conservative remapping. The method also supports parallel execution by accepting an optional communicator object for distributed computing environments. This caching mechanism improves performance when processing multiple variables or time steps on the same grid configuration by avoiding redundant remapper construction. Besides the per-plotter cache, the most recent regridder is kept at module level (keyed additionally by the source coordinates, weights directory and communicator), so the fresh plotter that each parallel task creates reuses the worker's regridder instead of rebuilding the ESMF weights for every time step.

        Parameters:
            lon_full (np.ndarray): 1D array of longitude coordinates for the full grid in degrees.
            lat_full (np.ndarray): 1D array of latitude coordinates for the full grid in degrees.
            lon_b (np.ndarray): 2D array of longitude coordinates for the cell boundaries in degrees.
            lat_b (np.ndarray): 2D array of latitude coordinates for the cell boundaries in degrees.
            lon_min (float): Western longitude bound in degrees for the target grid extent.
            lon_max (float): Eastern longitude bound in degrees for the target grid extent.
            lat_min (float): Southern latitude bound in degrees for the target grid extent.
            lat_max (float): Northern latitude bound in degrees for the target grid extent.
            resolution (float): Desired grid resolution in degrees for the target lat/lon grid.
            comm (Optional[Any]): Optional communicator object for parallel execution in distributed computing environments (default: None).

        Returns:
            MPASRemapper: An instance of MPASRemapper configured for conservative remapping from the full MPAS grid to the specified regular lat/lon grid, either retrieved from cache or newly built based on the provided parameters.
        """
        cache_key = (
            len(lon_full),
            round(lon_min, 6),
            round(lon_max, 6),
            round(lat_min, 6),
            round(lat_max, 6),
            round(resolution, 6),
            method,
            _array_fingerprint(lon_full),
            _array_fingerprint(lat_full),
            str(self._remapper_weights_dir),
            id(comm),
        )

        # The mesh, weights directory and communicator are part of the key, so a plotter reused for
        # another mesh of the same size never gets the previous mesh's regridder
        if self._remapper is not None and self._remapper_key == cache_key:
            return self._remapper

        remapper = _SHARED_REMAPPERS.get(cache_key)

        if remapper is None:
            remapper = MPASRemapper(
                method=method,
                reuse_weights=True,
                weights_dir=self._remapper_weights_dir,
                skipna=True,
            )

            remapper.prepare_source_grid(
                lon_full, lat_full, lon_bounds=lon_b, lat_bounds=lat_b
            )

            remapper.create_target_grid(
                lon_min=lon_min,
                lon_max=lon_max,
                lat_min=lat_min,
                lat_max=lat_max,
                dlon=resolution,
                dlat=resolution,
            )

            remapper.build_regridder(comm=comm)
            # Keep one regridder per process: its weights can be large on fine meshes
            _SHARED_REMAPPERS.clear()
            _SHARED_REMAPPERS[cache_key] = remapper

        self._remapper = remapper
        self._remapper_key = cache_key
        return self._remapper

    def _remap_conservative(
        self: "MPASVisualizer",
        data_full: np.ndarray,
        lon_full: np.ndarray,
        lat_full: np.ndarray,
        dataset: xr.Dataset,
        lon_min: float,
        lon_max: float,
        lat_min: float,
        lat_max: float,
        resolution: float,
        comm: Optional[Any] = None,
        method: str = "conservative",
    ) -> xr.DataArray:
        """
        This method performs conservative remapping of data values from the full MPAS grid to a regular lat/lon grid defined by the specified geographic bounds and resolution. It first ensures that the dataset contains the necessary boundary coordinate variables ('lon_b' and 'lat_b') for accurate remapping, then retrieves or builds an MPASRemapper instance configured for the current grid and remapping parameters. The method uses the remapper to perform the remapping operation, which conservatively redistributes data values while preserving integral properties across grid cells. The resulting remapped data is returned as an xarray DataArray with dimensions corresponding to the target lat/lon grid, suitable for plotting with pcolormesh or contourf on map projections. This functionality is essential for visualizing MPAS data that may be originally defined on an unstructured grid or at irregular locations, enabling consistent and accurate representation on regular lat/lon maps.

        Parameters:
            data_full (np.ndarray): 1D array of data values corresponding to the full MPAS grid points, typically obtained from back-mapping valid data to the full grid.
            lon_full (np.ndarray): 1D array of longitude coordinates for the full MPAS grid in degrees.
            lat_full (np.ndarray): 1D array of latitude coordinates for the full MPAS grid in degrees.
            dataset (xr.Dataset): An xarray Dataset containing the original MPAS grid information, which can be used by MPASRemapper for more accurate interpolation and remapping. This dataset should include the necessary variables for defining the source grid and its boundaries.
            lon_min (float): Western longitude bound in degrees for the target grid extent.
            lon_max (float): Eastern longitude bound in degrees for the target grid extent.
            lat_min (float): Southern latitude bound in degrees for the target grid extent.
            lat_max (float): Northern latitude bound in degrees for the target grid extent.
            resolution (float): Desired grid resolution in degrees for the target lat/lon grid.
            comm (Optional[Any]): Optional communicator object for parallel execution in distributed computing environments (default: None).

        Returns:
            xr.DataArray: An xarray DataArray containing the remapped data values on the regular lat/lon grid, with dimensions corresponding to the target grid coordinates. This DataArray is suitable for plotting with pcolormesh or contourf on map projections.
        """
        lon_b = dataset["lon_b"].values
        lat_b = dataset["lat_b"].values

        remapper = self._get_or_build_remapper(
            lon_full,
            lat_full,
            lon_b,
            lat_b,
            lon_min,
            lon_max,
            lat_min,
            lat_max,
            resolution,
            comm=comm,
            method=method,
        )

        return remapper.remap(xr.DataArray(data_full, dims=["nCells"]))

    def _interpolate_to_grid(
        self: "MPASVisualizer",
        lon: np.ndarray,
        lat: np.ndarray,
        data: np.ndarray,
        lon_min: float,
        lon_max: float,
        lat_min: float,
        lat_max: float,
        grid_resolution: Optional[float] = None,
        dataset: Optional[xr.Dataset] = None,
        method: str = "linear",
        resolution_bounds: Optional[Tuple[float, float]] = None,
        comm: Optional[Any] = None,
        config: Optional[Any] = None,
        interpolation: Optional[str] = None,
    ) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
        """
        This method performs interpolation of scattered data points defined by longitude, latitude, and corresponding values onto a regular lat/lon grid within specified geographic bounds. It uses the remap_mpas_to_latlon_with_masking function from MPASRemapper to handle the interpolation, which is optimized for MPAS data and can apply masking to exclude invalid points. The method allows for automatic selection of grid resolution based on the geographic extent, with optional bounds to prevent excessively coarse or fine grids. The resulting interpolated data is returned as 2D arrays corresponding to the meshgrid of longitude and latitude coordinates, suitable for use in contour or pcolormesh plots on map projections. This functionality is essential for visualizing MPAS data that may be originally defined on an unstructured grid or at irregular locations, enabling consistent and accurate representation on regular lat/lon maps.

        Parameters:
            lon (np.ndarray): 1D array of longitude coordinates for the input data points in degrees.
            lat (np.ndarray): 1D array of latitude coordinates for the input data points in degrees.
            data (np.ndarray): 1D array of data values corresponding to each (lon, lat) point, typically representing a variable of interest (e.g., temperature, wind speed).
            lon_min (float): Western longitude bound in degrees for the interpolation grid extent.
            lon_max (float): Eastern longitude bound in degrees for the interpolation grid extent.
            lat_min (float): Southern latitude bound in degrees for the interpolation grid extent.
            lat_max (float): Northern latitude bound in degrees for the interpolation grid extent.
            grid_resolution (Optional[float]): Desired grid resolution in degrees for the output lat/lon grid. If None, the method will automatically select a resolution based on the geographic extent (default: None).
            dataset (Optional[xr.Dataset]): Optional xarray Dataset containing the original MPAS grid information, which can be used by MPASRemapper for more accurate interpolation. If None, the method will attempt to create a minimal dataset from the provided lon and lat arrays (default: None).
            method (str): Interpolation method to use, options include 'nearest', 'linear', 'cubic', etc., as supported by MPASRemapper (default: 'linear').
            resolution_bounds (Optional[Tuple[float, float]]): Optional tuple specifying the minimum and maximum allowable grid resolution in degrees (default: None).
            comm (Optional[Any]): Optional communicator object for parallel execution in distributed computing environments (default: None).
            config (Optional[Any]): Optional configuration object that may contain settings for remapping engine and method, used to determine whether to use ESMPy or KDTree for interpolation (default: None).
            interpolation (Optional[str]): Explicit gridding method ('nearest', 'linear' or 'cubic'). When given it overrides method and config.remap_method and selects the KDTree gridder unless the config explicitly requests the ESMF engine (default: None).

        Returns:
            Tuple[np.ndarray, np.ndarray, np.ndarray]: A tuple containing the longitude meshgrid, latitude meshgrid, and interpolated data array on the regular lat/lon grid, suitable for plotting on map projections. The longitude and latitude meshgrids correspond to the coordinates of the interpolated data points.
        """
        # Determine grid resolution in degrees
        resolution = self._determine_grid_resolution(
            grid_resolution, lon_min, lon_max, lat_min, lat_max, resolution_bounds
        )

        # Determine engine and method from config, or auto-select legacy behaviour.
        engine = getattr(config, "remap_engine", None) if config else None
        esmf_method = (
            getattr(config, "remap_method", "conservative")
            if config
            else "conservative"
        )
        kdtree_method = getattr(config, "remap_method", method) if config else method

        # An explicit interpolation choice wins over the plotter default and the config method
        if interpolation is not None:
            kdtree_method = interpolation

        use_esmf = engine == "esmf" or (  # explicit engine request
            engine is None  # legacy auto-select
            and interpolation is None
            and ESMPY_AVAILABLE
            and self._has_boundary_data(self._ensure_boundary_data(dataset))
        )

        # --- ESMPy path (returns None to fall back to KDTree) ---
        if use_esmf:
            esmf_result = self._attempt_esmf_remap(
                lon,
                lat,
                data,
                lon_min,
                lon_max,
                lat_min,
                lat_max,
                resolution,
                dataset,
                engine,
                esmf_method,
                comm,
            )
            if esmf_result is not None:
                return esmf_result

        # --- KDTree path ---
        return self._kdtree_interpolate(
            lon,
            lat,
            data,
            lon_min,
            lon_max,
            lat_min,
            lat_max,
            resolution,
            dataset,
            kdtree_method,
        )

    @staticmethod
    def _determine_grid_resolution(
        grid_resolution: Optional[float],
        lon_min: float,
        lon_max: float,
        lat_min: float,
        lat_max: float,
        resolution_bounds: Optional[Tuple[float, float]],
    ) -> float:
        """
        This static method determines the appropriate grid resolution in degrees for interpolating data onto a regular lat/lon grid based on the provided geographic bounds and an optional explicit resolution. If an explicit grid_resolution is provided and is greater than zero, it is used directly. Otherwise, the method calculates a default resolution by dividing the longitude and latitude ranges by 100 to create a grid with approximately 100 points along each dimension. If resolution_bounds are provided, the calculated resolution is clamped to be within the specified minimum and maximum bounds. This approach ensures that the resulting grid is neither too coarse nor too fine for typical visualization purposes, while also allowing for user control when needed.

        Parameters:
            grid_resolution (Optional[float]): Explicit desired grid resolution in degrees, or None to auto-select from the geographic extent.
            lon_min (float): Western longitude bound in degrees.
            lon_max (float): Eastern longitude bound in degrees.
            lat_min (float): Southern latitude bound in degrees.
            lat_max (float): Northern latitude bound in degrees.
            resolution_bounds (Optional[Tuple[float, float]]): Optional (min, max) bounds in degrees used to clamp an auto-selected resolution.

        Returns:
            float: The resolved grid resolution in degrees.
        """
        if grid_resolution is not None:
            resolution = float(grid_resolution)
            if resolution <= 0:
                raise ValueError("grid_resolution must be > 0")
            return resolution

        lon_range = lon_max - lon_min
        lat_range = lat_max - lat_min

        resolution = max(lon_range / 100, lat_range / 100)

        if resolution_bounds is not None:
            resolution_min, resolution_max = resolution_bounds
            resolution = max(resolution_min, min(resolution, resolution_max))

        return resolution

    def _attempt_esmf_remap(
        self: "MPASVisualizer",
        lon: np.ndarray,
        lat: np.ndarray,
        data: np.ndarray,
        lon_min: float,
        lon_max: float,
        lat_min: float,
        lat_max: float,
        resolution: float,
        dataset: Optional[xr.Dataset],
        engine: Optional[str],
        esmf_method: str,
        comm: Optional[Any],
    ) -> Optional[Tuple[np.ndarray, np.ndarray, np.ndarray]]:
        """
        This method attempts to perform conservative remapping of the input data onto a regular lat/lon grid using the ESMPy library. It first checks if the necessary boundary data is available in the dataset, and if not, it either raises an error (if ESMPy was explicitly requested) or returns None to indicate that the remapping cannot be performed with ESMPy. If boundary data is available, it extracts the full grid coordinates, back-maps the valid data points to the full grid, and then uses an MPASRemapper instance to perform the conservative remapping. The resulting remapped data is returned as a tuple of longitude meshgrid, latitude meshgrid, and remapped values. If any step in this process fails (e.g., due to missing data or issues with ESMPy), it logs a warning and returns None to allow for a fallback to KDTree interpolation.

        Parameters:
            lon (np.ndarray): 1D array of longitude coordinates for the input points.
            lat (np.ndarray): 1D array of latitude coordinates for the input points.
            data (np.ndarray): 1D array of data values for each (lon, lat) point.
            lon_min (float): Western longitude bound in degrees for the output grid.
            lon_max (float): Eastern longitude bound in degrees for the output grid.
            lat_min (float): Southern latitude bound in degrees for the output grid.
            lat_max (float): Northern latitude bound in degrees for the output grid.
            resolution (float): Output grid resolution in degrees.
            dataset (Optional[xr.Dataset]): Dataset providing the MPAS grid information.
            engine (Optional[str]): Requested remap engine ('esmf' forces ESMPy).
            esmf_method (str): The ESMPy remap method (e.g. 'conservative').
            comm (Optional[Any]): Optional communicator for parallel execution.

        Returns:
            Optional[Tuple[np.ndarray, np.ndarray, np.ndarray]]: The (lon_mesh, lat_mesh, values) tuple on success, or None to fall back to KDTree.
        """
        dataset = self._ensure_boundary_data(dataset)

        if not self._has_boundary_data(dataset):
            if engine == "esmf":
                raise ValueError(
                    "remap_engine='esmf' requires boundary coordinates "
                    "('lon_b'/'lat_b') in the dataset."
                )
            return None

        try:
            lon_full, lat_full = self._extract_full_grid(dataset)
            full_data = self._backmap_to_full_grid(lon, lat, data, lon_full, lat_full)

            logger.info(
                "Remapping %s cells via ESMPy/%s (resolution %.3f°)",
                f"{len(lon_full):,}",
                esmf_method,
                resolution,
            )

            remap_result = self._remap_conservative(
                full_data,
                lon_full,
                lat_full,
                dataset,
                lon_min,
                lon_max,
                lat_min,
                lat_max,
                resolution,
                comm=comm,
                method=esmf_method,
            )

            lon_mesh, lat_mesh = np.meshgrid(
                remap_result.lon.values, remap_result.lat.values
            )  # type: np.ndarray, np.ndarray
            return lon_mesh, lat_mesh, remap_result.values
        except Exception as exc:
            if engine == "esmf":
                raise

            logger.warning(
                "ESMPy/%s remapping failed (%s); falling back to KD-Tree.",
                esmf_method,
                exc,
            )

            return None

    def _kdtree_interpolate(
        self: "MPASVisualizer",
        lon: np.ndarray,
        lat: np.ndarray,
        data: np.ndarray,
        lon_min: float,
        lon_max: float,
        lat_min: float,
        lat_max: float,
        resolution: float,
        dataset: Optional[xr.Dataset],
        kdtree_method: str,
    ) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
        """
        This method performs interpolation of scattered data points onto a regular lat/lon grid using a KDTree-based approach. It first checks if a dataset is provided, and if not, it constructs a minimal xarray Dataset from the provided longitude and latitude arrays to facilitate the use of the remap_mpas_to_latlon_with_masking function. The method then calls this function with the specified parameters to perform the interpolation, which uses a KDTree for efficient nearest-neighbor searching. The resulting interpolated data is returned as 2D arrays corresponding to the meshgrid of longitude and latitude coordinates, suitable for plotting on map projections. This method serves as a fallback when ESMPy remapping is not available or fails, providing a robust alternative for visualizing MPAS data on regular lat/lon grids.

        Parameters:
            lon (np.ndarray): 1D array of longitude coordinates for the input points.
            lat (np.ndarray): 1D array of latitude coordinates for the input points.
            data (np.ndarray): 1D array of data values for each (lon, lat) point.
            lon_min (float): Western longitude bound in degrees for the output grid.
            lon_max (float): Eastern longitude bound in degrees for the output grid.
            lat_min (float): Southern latitude bound in degrees for the output grid.
            lat_max (float): Northern latitude bound in degrees for the output grid.
            resolution (float): Output grid resolution in degrees.
            dataset (Optional[xr.Dataset]): Dataset providing the MPAS grid information, or None to build a minimal one from ``lon``/``lat``.
            kdtree_method (str): Interpolation method for the KDTree remapper.

        Returns:
            Tuple[np.ndarray, np.ndarray, np.ndarray]: The longitude meshgrid, latitude meshgrid, and interpolated data array on the regular lat/lon grid.
        """
        logger.info(
            "Interpolating %d points using KDTree (%s)", len(data), kdtree_method
        )

        if dataset is None:
            lon_arr = lon if isinstance(lon, np.ndarray) else lon.values
            lat_arr = lat if isinstance(lat, np.ndarray) else lat.values
            dataset = xr.Dataset(
                {
                    "lonCell": xr.DataArray(lon_arr, dims=["nCells"]),
                    "latCell": xr.DataArray(lat_arr, dims=["nCells"]),
                }
            )

        data_xr = xr.DataArray(
            self._align_to_dataset(dataset, lon, lat, data), dims=["nCells"]
        )

        remapped_result = remap_mpas_to_latlon_with_masking(
            data=data_xr,
            dataset=dataset,
            lon_min=lon_min,
            lon_max=lon_max,
            lat_min=lat_min,
            lat_max=lat_max,
            resolution=resolution,
            method=kdtree_method,
            apply_mask=True,
            lon_convention="auto",
        )

        lon_coords = remapped_result.lon.values
        lat_coords = remapped_result.lat.values
        lon_mesh, lat_mesh = np.meshgrid(
            lon_coords, lat_coords
        )  # type: np.ndarray, np.ndarray
        data_interp = remapped_result.values

        logger.debug(
            "KDTree produced %dx%d grid", data_interp.shape[0], data_interp.shape[1]
        )
        return lon_mesh, lat_mesh, data_interp

    @staticmethod
    def _norm_limits(
        norm: Optional[mcolors.Normalize],
    ) -> Tuple[Optional[float], Optional[float]]:
        """
        This helper returns the lower and upper colour limits a normalization represents: the first and last boundary of a BoundaryNorm, or vmin and vmax of any other Normalize that has them set. It is the single place that tells the colorbar code which data values lie inside the coloured range, so the extend arrows can be derived from the plotted data instead of being hard-coded.

        Parameters:
            norm (Optional[mcolors.Normalize]): Normalization instance, or None when matplotlib autoscales.

        Returns:
            Tuple[Optional[float], Optional[float]]: The (lower, upper) limits, each None when the normalization does not define one.
        """
        if norm is None:
            return None, None

        if isinstance(norm, mcolors.BoundaryNorm):
            bounds = np.asarray(norm.boundaries, dtype=float)
            return float(bounds[0]), float(bounds[-1])

        vmin = getattr(norm, "vmin", None)
        vmax = getattr(norm, "vmax", None)
        return (
            None if vmin is None else float(vmin),
            None if vmax is None else float(vmax),
        )

    @staticmethod
    def _derive_extend(
        data: Optional[np.ndarray], lower: Optional[float], upper: Optional[float]
    ) -> str:
        """
        This helper decides which colorbar extend arrows are needed by comparing the plotted data with the coloured range. An arrow is drawn at the low end only when finite plotted values fall below the lower limit and at the high end only when values exceed the upper limit; when every value lies inside the range (or a limit is unknown) no arrow is drawn, so the colorbar never advertises out-of-range values that do not exist.

        Parameters:
            data (Optional[np.ndarray]): The values that are actually plotted (non-finite entries are ignored).
            lower (Optional[float]): Lowest value of the coloured range, or None when unbounded.
            upper (Optional[float]): Highest value of the coloured range, or None when unbounded.

        Returns:
            str: One of 'neither', 'min', 'max' or 'both'.
        """
        if data is None:
            return "neither"

        values = np.asarray(data, dtype=float)
        values = values[np.isfinite(values)]

        if values.size == 0:
            return "neither"

        below = lower is not None and bool(values.min() < lower)
        above = upper is not None and bool(values.max() > upper)

        if below and above:
            return "both"
        if below:
            return "min"
        if above:
            return "max"
        return "neither"

    def _create_scatter_plot(
        self: "MPASVisualizer",
        lon: np.ndarray,
        lat: np.ndarray,
        data: np.ndarray,
        cmap_obj: Union[str, mcolors.Colormap],
        norm: Optional[mcolors.Normalize],
        data_crs: ccrs.CRS,
        colorbar_label: Optional[str] = None,
        colorbar_ticks: Optional[List[float]] = None,
        extend: Optional[str] = None,
    ) -> None:
        """
        This method creates a scatter plot of data points colored by their corresponding values, with an optional colorbar for reference. It calculates an adaptive marker size based on the geographic extent and density of points to ensure that the plot is informative without being overly cluttered. The method sorts the data points by their values to improve visualization of overlapping points, and applies the specified colormap and normalization for accurate color representation. It also adds a colorbar with appropriate labeling and tick formatting to provide context for interpreting the colors in terms of the underlying data values. This scatter plot is useful for visualizing spatial patterns in MPAS data, such as temperature or precipitation at specific locations, while maintaining clarity even in dense datasets.

        Parameters:
            lon (np.ndarray): 1D array of longitude coordinates for the data points in degrees.
            lat (np.ndarray): 1D array of latitude coordinates for the data points in degrees.
            data (np.ndarray): 1D array of data values corresponding to each (lon, lat) point, typically representing a variable of interest (e.g., temperature, precipitation).
            cmap_obj (Union[str, mcolors.Colormap]): Colormap instance or name to use for coloring the data points based on their values.
            norm (Optional[mcolors.Normalize]): Optional normalization instance to control the mapping of data values to colors, allowing for custom scaling (e.g., logarithmic) if desired.
            data_crs (ccrs.CRS): Coordinate reference system for the input data points, used for accurate plotting on the map projection.
            colorbar_label (Optional[str]): Label for the colorbar to indicate the variable and units being represented by the colors (default: None, which will attempt to build a label from variable metadata if available).
            colorbar_ticks (Optional[List[float]]): Optional list of specific tick values to set on the colorbar for better readability, especially if the data range is known and a limited number of ticks is desired (default: None, which will use automatic tick placement by matplotlib).
            extend (Optional[str]): Explicit colorbar extend mode ('neither', 'min', 'max' or 'both'); when None it is derived from the plotted data against the colour limits of the normalization (default: None).

        Returns:
            None: Modifies self.ax by adding a scatter plot of the data points colored by their values, and adds a colorbar if applicable. Raises AssertionError if self.ax or self.fig is None, indicating that the plotting area must be set up before calling this method.
        """
        assert self.ax is not None, "Axes must be created before scatter plot"
        assert self.fig is not None, "Figure must be created before scatter plot"

        map_extent = (lon.min(), lon.max(), lat.min(), lat.max())
        fig_size = (self.figsize[0], self.figsize[1])
        marker_size = self.calculate_adaptive_marker_size(
            map_extent, len(data), fig_size
        )

        map_area = (map_extent[1] - map_extent[0]) * (map_extent[3] - map_extent[2])
        point_density = len(data) / map_area if map_area > 0 else 0
        alpha_val = 0.8 if point_density > 1000 else 0.9

        sort_indices = np.argsort(data)
        lon_sorted = lon[sort_indices]
        lat_sorted = lat[sort_indices]
        data_sorted = data[sort_indices]

        scatter = self.ax.scatter(
            lon_sorted,
            lat_sorted,
            c=data_sorted,
            cmap=cmap_obj,
            norm=norm,
            s=marker_size,
            alpha=alpha_val,
            transform=data_crs,
            edgecolors="none",
        )

        if extend is None:
            extend = self._derive_extend(data, *self._norm_limits(norm))

        try:
            if colorbar_label is None:
                colorbar_label = MPASVisualizationStyle.build_colorbar_label(
                    getattr(self, "_current_var_metadata", None)
                )

            colorbar = MPASVisualizationStyle.add_colorbar(
                self.fig,
                self.ax,
                scatter,
                label=colorbar_label,
                orientation="horizontal",
                extend=extend,
                fraction=0.04,
                pad=0.06,
                shrink=0.8,
                fmt=None,
                labelpad=-60,
                label_pos="top",
                tick_labelsize=8,
            )

            if colorbar is not None:
                if colorbar_ticks is not None and len(colorbar_ticks) <= 15:
                    colorbar.set_ticks(colorbar_ticks)
                    colorbar.set_ticklabels(self._format_ticks_dynamic(colorbar_ticks))
                else:
                    ticks = colorbar.get_ticks().tolist()
                    colorbar.set_ticks(ticks)
                    colorbar.set_ticklabels(self._format_ticks_dynamic(ticks))
                colorbar.ax.tick_params(labelsize=8)
        except Exception:
            pass

    def _create_contour_plot(
        self: "MPASVisualizer",
        lon: np.ndarray,
        lat: np.ndarray,
        data: np.ndarray,
        bounds: GeographicBounds,
        cmap_obj: Union[str, mcolors.Colormap],
        norm: Optional[mcolors.Normalize],
        levels: Optional[List[float]],
        data_crs: ccrs.CRS,
        grid_resolution: Optional[float] = None,
        dataset: Optional[xr.Dataset] = None,
        config: Optional[Any] = None,
        interpolation: Optional[str] = None,
    ) -> None:
        """
        This method creates a contour plot by interpolating scattered data points onto a regular lat/lon grid and then using matplotlib's contour function to draw contour lines. It first calls the _interpolate_to_grid method to perform the interpolation using MPASRemapper, which handles the complexities of remapping MPAS data onto a regular grid. The method then creates contour lines based on the interpolated data, with options for specifying explicit contour levels or allowing matplotlib to determine them automatically. It also attempts to add inline labels to the contours for better readability. This contour plot is useful for visualizing spatial gradients and patterns in MPAS data, such as pressure or temperature fields, while ensuring that the underlying data is accurately represented on the map projection.

        Parameters:
            lon (np.ndarray): 1D array of longitude coordinates for the input data points in degrees.
            lat (np.ndarray): 1D array of latitude coordinates for the input data points in degrees.
            data (np.ndarray): 1D array of data values corresponding to each (lon, lat) point, typically representing a variable of interest (e.g., temperature, pressure).
            bounds (GeographicBounds): Interpolation grid extent as (lon_min, lon_max, lat_min, lat_max) longitude/latitude boundaries in degrees.
            cmap_obj (Union[str, mcolors.Colormap]): Colormap instance or name to use for coloring the contour lines based on their values.
            norm (Optional[mcolors.Normalize]): Optional normalization instance to control the mapping of data values to colors for the contour lines, allowing for custom scaling if desired.
            levels (Optional[List[float]]): Optional list of specific contour levels to draw, which can help highlight particular values of interest in the data. If None, matplotlib will automatically determine contour levels based on the data range (default: None).
            data_crs (ccrs.CRS): Coordinate reference system for the input data points, used for accurate plotting on the map projection.
            grid_resolution (Optional[float]): Desired grid resolution in degrees for the interpolation step, which can affect the smoothness and accuracy of the contour lines. If None, the method will automatically select a resolution based on the geographic extent (default: None).
            dataset (Optional[xr.Dataset]): Optional xarray Dataset containing the original MPAS grid information, which can be used by MPASRemapper for more accurate interpolation. If None, the method will attempt to create a minimal dataset from the provided lon and lat arrays (default: None).
            interpolation (Optional[str]): Optional gridding method ('nearest', 'linear' or 'cubic') that takes precedence over the plotter default and over config.remap_method (default: None).

        Returns:
            None: Modifies self.ax by adding contour lines based on the interpolated data, raises AssertionError if self.ax or self.fig is None, indicating that the plotting area must be set up before calling this method.
        """
        assert self.ax is not None, "Axes must be created before contour plot"
        assert self.fig is not None, "Figure must be created before contour plot"

        lon_min, lon_max, lat_min, lat_max = bounds

        lon_mesh, lat_mesh, data_interp = self._interpolate_to_grid(
            lon,
            lat,
            data,
            lon_min,
            lon_max,
            lat_min,
            lat_max,
            grid_resolution,
            dataset,
            config=config,
            interpolation=interpolation,
        )

        try:
            if levels is not None:
                contour_set = self.ax.contour(
                    lon_mesh,
                    lat_mesh,
                    data_interp,
                    levels=levels,
                    colors="black",
                    linewidths=1.0,
                    linestyles="solid",
                    transform=data_crs,
                )
            else:
                contour_set = self.ax.contour(
                    lon_mesh,
                    lat_mesh,
                    data_interp,
                    colors="black",
                    linewidths=1.0,
                    linestyles="solid",
                    transform=data_crs,
                )

            if levels is not None:
                try:
                    self.ax.clabel(contour_set, inline=True, fontsize=8, fmt="%g")
                except Exception:
                    pass
        except Exception as e:
            raise RuntimeError(f"Contour plotting failed: {e}")

    def _create_contourf_plot(
        self: "MPASVisualizer",
        lon: np.ndarray,
        lat: np.ndarray,
        data: np.ndarray,
        bounds: GeographicBounds,
        cmap_obj: Union[str, mcolors.Colormap],
        norm: Optional[mcolors.Normalize],
        levels: Optional[List[float]],
        data_crs: ccrs.CRS,
        grid_resolution: Optional[float] = None,
        dataset: Optional[xr.Dataset] = None,
        colorbar_label: Optional[str] = None,
        colorbar_ticks: Optional[List[float]] = None,
        config: Optional[Any] = None,
        interpolation: Optional[str] = None,
    ) -> None:
        """
        This method creates a filled contour plot by interpolating scattered data points onto a regular lat/lon grid and then using matplotlib's contourf function to draw filled contours. It first calls the _interpolate_to_grid method to perform the interpolation using MPASRemapper, which handles the complexities of remapping MPAS data onto a regular grid. The method then creates filled contour areas based on the interpolated data, with options for specifying explicit contour levels or allowing matplotlib to determine them automatically. It also adds a colorbar to the plot with appropriate labeling and tick formatting to provide context for interpreting the colors in terms of the underlying data values. This filled contour plot is useful for visualizing spatial patterns and gradients in MPAS data, such as temperature or precipitation fields, while ensuring that the underlying data is accurately represented on the map projection.

        Parameters:
            lon (np.ndarray): 1D array of longitude coordinates for the input data points in degrees.
            lat (np.ndarray): 1D array of latitude coordinates for the input data points in degrees.
            data (np.ndarray): 1D array of data values corresponding to each (lon, lat) point, typically representing a variable of interest (e.g., temperature, precipitation).
            bounds (GeographicBounds): Interpolation grid extent as (lon_min, lon_max, lat_min, lat_max) longitude/latitude boundaries in degrees.
            cmap_obj (Union[str, mcolors.Colormap]): Colormap instance or name to use for coloring the filled contours based on their values.
            norm (Optional[mcolors.Normalize]): Optional normalization instance to control the mapping of data values to colors for the filled contours, allowing for custom scaling if desired.
            levels (Optional[List[float]]): Optional list of specific contour levels to draw, which can help highlight particular values of interest in the data. If None, matplotlib will automatically determine contour levels based on the data range (default: None).
            data_crs (ccrs.CRS): Coordinate reference system for the input data points, used for accurate plotting on the map projection.
            grid_resolution (Optional[float]): Desired grid resolution in degrees for the interpolation step, which can affect the smoothness and accuracy of the filled contours. If None, the method will automatically select a resolution based on the geographic extent (default: None).
            dataset (Optional[xr.Dataset]): Optional xarray Dataset containing the original MPAS grid information, which can be used by MPASRemapper for more accurate interpolation. If None, the method will attempt to create a minimal dataset from the provided lon and lat arrays (default: None).
            colorbar_label (Optional[str]): Label for the colorbar to indicate the variable and units being represented by the colors (default: None, which will attempt to build a label from variable metadata if available).
            colorbar_ticks (Optional[List[float]]): Optional list of specific tick values to set on the colorbar for better readability, especially if the data range is known and a limited number of ticks is desired (default: None, which will use automatic tick placement by matplotlib).
            interpolation (Optional[str]): Optional gridding method ('nearest', 'linear' or 'cubic') that takes precedence over the plotter default and over config.remap_method (default: None).

        Returns:
            None: Modifies self.ax by adding filled contours. The colorbar extend arrows are derived from the interpolated data against the first and last level (or the colour limits of the normalization), so an arrow only appears when plotted values actually fall outside the coloured range. based on the interpolated data, and adds a colorbar if applicable. Raises AssertionError if self.ax or self.fig is None, indicating that the plotting area must be set up before calling this method.
        """
        assert self.ax is not None, "Axes must be created before contourf plot"
        assert self.fig is not None, "Figure must be created before contourf plot"

        lon_min, lon_max, lat_min, lat_max = bounds

        lon_mesh, lat_mesh, data_interp = self._interpolate_to_grid(
            lon,
            lat,
            data,
            lon_min,
            lon_max,
            lat_min,
            lat_max,
            grid_resolution,
            dataset,
            config=config,
            interpolation=interpolation,
        )

        # Derive the colorbar extend arrows from the plotted (gridded) data versus the coloured range
        if levels is not None:
            extend = self._derive_extend(
                data_interp, float(np.min(levels)), float(np.max(levels))
            )
            contour_set = self.ax.contourf(
                lon_mesh,
                lat_mesh,
                data_interp,
                levels=levels,
                cmap=cmap_obj,
                norm=norm,
                transform=data_crs,
                extend=extend,
            )
        else:
            extend = self._derive_extend(data_interp, *self._norm_limits(norm))
            contour_set = self.ax.contourf(
                lon_mesh,
                lat_mesh,
                data_interp,
                cmap=cmap_obj,
                norm=norm,
                transform=data_crs,
            )

        self._add_map_colorbar(contour_set, extend, colorbar_label, colorbar_ticks)

    def _add_map_colorbar(
        self: "MPASVisualizer",
        mappable: Any,
        extend: str,
        colorbar_label: Optional[str] = None,
        colorbar_ticks: Optional[List[float]] = None,
    ) -> None:
        """
        This helper adds the standard horizontal map colorbar for a filled-contour or pcolormesh layer, with a label (built from the current variable metadata when none is given), dynamically formatted ticks (the given ticks when there are at most 15 of them) and the requested extend arrows. A failure to build the colorbar is swallowed so the map itself is still returned.

        Parameters:
            mappable (Any): The ContourSet or QuadMesh the colorbar describes.
            extend (str): Colorbar extend mode ('neither', 'min', 'max' or 'both').
            colorbar_label (Optional[str]): Label for the colorbar; None builds one from the variable metadata.
            colorbar_ticks (Optional[List[float]]): Optional explicit tick values.

        Returns:
            None: Adds the colorbar to self.fig next to self.ax.
        """
        try:
            if colorbar_label is None:
                colorbar_label = MPASVisualizationStyle.build_colorbar_label(
                    getattr(self, "_current_var_metadata", None)
                )

            colorbar = MPASVisualizationStyle.add_colorbar(
                self.fig,
                self.ax,
                mappable,
                label=colorbar_label,
                orientation="horizontal",
                extend=extend,
                fraction=0.04,
                pad=0.06,
                shrink=0.8,
                fmt=None,
                labelpad=-60,
                label_pos="top",
                tick_labelsize=8,
            )

            if colorbar is not None:
                if colorbar_ticks is not None and len(colorbar_ticks) <= 15:
                    colorbar.set_ticks(colorbar_ticks)
                    colorbar.set_ticklabels(self._format_ticks_dynamic(colorbar_ticks))
                else:
                    ticks = colorbar.get_ticks().tolist()
                    colorbar.set_ticks(ticks)
                    colorbar.set_ticklabels(self._format_ticks_dynamic(ticks))
                colorbar.ax.tick_params(labelsize=8)
        except Exception:
            pass

    def _create_pcolormesh_plot(
        self: "MPASVisualizer",
        lon: np.ndarray,
        lat: np.ndarray,
        data: np.ndarray,
        bounds: GeographicBounds,
        cmap_obj: Union[str, mcolors.Colormap],
        norm: Optional[mcolors.Normalize],
        levels: Optional[List[float]],
        data_crs: ccrs.CRS,
        grid_resolution: Optional[float] = None,
        dataset: Optional[xr.Dataset] = None,
        colorbar_label: Optional[str] = None,
        colorbar_ticks: Optional[List[float]] = None,
        config: Optional[Any] = None,
        interpolation: Optional[str] = None,
    ) -> None:
        """
        This method draws the data as a pcolormesh (one coloured cell per grid box) after gridding the scattered points onto a regular lat/lon grid exactly as the filled-contour plot does, and colours it with the same normalization and levels. It adds the standard colorbar whose extend arrows are derived from the gridded data against the first and last level (or the colour limits of the normalization). It is the renderer behind plot_type='pcolormesh' and is useful when the discrete grid cells, rather than smoothed contour bands, should be visible.

        Parameters:
            lon (np.ndarray): 1D array of longitude coordinates for the input data points in degrees.
            lat (np.ndarray): 1D array of latitude coordinates for the input data points in degrees.
            data (np.ndarray): 1D array of data values corresponding to each (lon, lat) point.
            bounds (GeographicBounds): Gridding extent as (lon_min, lon_max, lat_min, lat_max) in degrees.
            cmap_obj (Union[str, mcolors.Colormap]): Colormap instance or name.
            norm (Optional[mcolors.Normalize]): Optional normalization instance controlling the colour mapping.
            levels (Optional[List[float]]): Optional contour levels used to derive the colorbar extend arrows.
            data_crs (ccrs.CRS): Coordinate reference system of the input points.
            grid_resolution (Optional[float]): Grid resolution in degrees (None selects one from the extent).
            dataset (Optional[xr.Dataset]): Optional dataset with the MPAS grid information used by the remapper.
            colorbar_label (Optional[str]): Colorbar label (None builds one from the variable metadata).
            colorbar_ticks (Optional[List[float]]): Optional explicit colorbar ticks.
            config (Optional[Any]): Optional configuration with remapping settings.
            interpolation (Optional[str]): Optional gridding method ('nearest', 'linear' or 'cubic') overriding the default.

        Returns:
            None: Modifies self.ax by adding the pcolormesh layer and a colorbar; raises AssertionError if self.ax or self.fig is None.
        """
        assert self.ax is not None, "Axes must be created before pcolormesh plot"
        assert self.fig is not None, "Figure must be created before pcolormesh plot"

        lon_min, lon_max, lat_min, lat_max = bounds

        lon_mesh, lat_mesh, data_interp = self._interpolate_to_grid(
            lon,
            lat,
            data,
            lon_min,
            lon_max,
            lat_min,
            lat_max,
            grid_resolution,
            dataset,
            config=config,
            interpolation=interpolation,
        )

        if levels is not None:
            extend = self._derive_extend(
                data_interp, float(np.min(levels)), float(np.max(levels))
            )
        else:
            extend = self._derive_extend(data_interp, *self._norm_limits(norm))

        mesh = self.ax.pcolormesh(
            lon_mesh,
            lat_mesh,
            np.ma.masked_invalid(data_interp),
            cmap=cmap_obj,
            norm=norm,
            transform=data_crs,
            shading="auto",
        )

        self._add_map_colorbar(mesh, extend, colorbar_label, colorbar_ticks)
